export function medsForGrade(grade: ClinicalGrade, controlledOnly = false) {
  return PHECC_FORMULARY.filter(
    (m) => m.grades.includes(grade) && (controlledOnly ? m.controlled : !m.controlled),
  )
}

export function controlledMedsForGrade(grade: 'Paramedic' | 'AP') {
  return PHECC_FORMULARY.filter((m) => m.controlled && m.grades.includes(grade))
}

export function formularyById(id: string): MedicationDef | undefined {
  return PHECC_FORMULARY.find((m) => m.id === id)
}

/** Fill missing profile fields from formulary (legacy stock / cloud rows). */
export function enrichStockProfile<T extends { medicationId: string; unit: string }>(
  item: T,
): T & {
  strength: string
  doseUnit: DoseUnit
  stockUnit: StockUnit
  packSize: number
  unit: string
} {
  const def = formularyById(item.medicationId)
  const anyItem = item as T & {
    strength?: string
    doseUnit?: DoseUnit
    stockUnit?: StockUnit
    packSize?: number
  }
  return {
    ...item,
    strength: anyItem.strength ?? def?.strength ?? '—',
    doseUnit: anyItem.doseUnit ?? def?.doseUnit ?? 'unit',
    stockUnit: anyItem.stockUnit ?? def?.stockUnit ?? (item.unit as StockUnit) ?? 'unit',
    packSize: anyItem.packSize ?? def?.packSize ?? 1,
    unit: item.unit || def?.stockUnit || 'unit',
  }
}
